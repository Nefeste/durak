// Строка над рукой «к этой минуте» (docs/09-game-design.md, «Подсказки и счёт карт»): совет «Подсказки» и «так нельзя:
// …» относятся к той позиции, где их спросили. Любое следующее действие за столом — своё или соперника — их гасит
// (игра владельца 09.11.2026: «Берите» висело несколько сдач). Метка позиции — что угодно, что меняется с каждым
// действием: запись партии (новая на каждое действие и отмену) или номер хода онлайн.
export interface Note<At = unknown> {
  text: string;
  /** Позиция, к которой строка относится. */
  at: At;
}

/** Что показать сейчас: строку — только пока позиция та же. */
export const noteOf = <At>(n: Note<At> | null, at: At): string | null => (n !== null && n.at === at ? n.text : null);
