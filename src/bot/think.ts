// Ход бота кусками. Бот, которому есть о чём думать, отдаёт генератор: `yield` после каждой
// порции работы. Генератор получает из `yield` сигнал «хватит»: тогда он возвращает лучший
// ход из уже досчитанных.
//
// Бюджет в приложении — время, в симуляторе — число порций: так замеры воспроизводимы,
// а на медленном телефоне бот чуть слабее, а не медленнее.

/** Размышление бота: `yield` — порция готова; `true` в ответ — пора отвечать. */
export type Thinking<R> = Generator<void, R, boolean | undefined>;

/** Досчитать до конца или до `maxSteps` порций — синхронно, для симулятора и тестов. */
export function thinkSync<R>(t: Thinking<R>, maxSteps = Infinity): R {
  let steps = 0;
  for (let r = t.next(); ; r = t.next(++steps >= maxSteps)) if (r.done) return r.value;
}
